// Build the demo: bundle web/src/app.ts (+ the shared engine) into public/,
// and copy the recorded example runs. Usage: node web/build.mjs
import { build } from "esbuild";
import { copyFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
await build({
  entryPoints: [join(here, "src/app.ts")],
  bundle: true,
  format: "esm",
  minify: true,
  sourcemap: true,
  target: "es2020",
  outfile: join(here, "public/app.js"),
  loader: { ".png": "dataurl", ".svg": "dataurl" },
  external: ["/fonts/*"],
  nodePaths: [join(root, "node_modules"), ...(process.env.EXTRA_NODE_PATH ? [process.env.EXTRA_NODE_PATH] : [])],
  logLevel: "info",
});
mkdirSync(join(here, "public/examples"), { recursive: true });
for (const d of readdirSync(join(root, "examples"))) {
  const f = join(root, "examples", d, "result.json");
  if (existsSync(f)) copyFileSync(f, join(here, "public/examples", `${d}.json`));
}

// Embed public/ into the Worker bundle (worker/assets.gen.ts). Wrangler's
// separate asset-upload step is not usable from every CI/proxy setup, and the
// whole site is ~1 MB, well inside the Workers script limit.
import { readFileSync, writeFileSync, statSync } from "node:fs";
const types = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".json": "application/json", ".svg": "image/svg+xml", ".woff2": "font/woff2", ".txt": "text/plain; charset=utf-8", ".png": "image/png", ".jpg": "image/jpeg" };
const files = {};
const walk = (dir, base = "") => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, `${base}/${f}`);
    else if (!f.endsWith(".map")) {
      const ext = f.slice(f.lastIndexOf("."));
      files[`${base}/${f}`] = { type: types[ext] ?? "application/octet-stream", b64: readFileSync(p).toString("base64") };
    }
  }
};
walk(join(here, "public"));
writeFileSync(join(here, "worker/assets.gen.ts"), `// generated by web/build.mjs — do not edit\nexport const ASSETS: Record<string, { type: string; b64: string }> = ${JSON.stringify(files)};\n`);
console.log(`embedded ${Object.keys(files).length} files into worker/assets.gen.ts`);
